def replace_name_desc_tags(yaml: str, new_name: str, new_desc: str, extra_tags: list[str]) -> str:
    # Replace name and description (the first occurrences are the slot-level ones)
    import re
    yaml = re.sub(r'^name: "[^"]*"', f'name: "{new_name}"', yaml, count=1, flags=re.MULTILINE)
    yaml = re.sub(r'^description: "[^"]*"', f'description: "{new_desc}"', yaml, count=1, flags=re.MULTILINE)
    # Rewrite wandb.tags line: replace "packet-5"/"rlp5" with "packet-6"/"rlp6" and append extras
    # Simplest: find the wandb.tags line and append extras before the final ]
    def tag_sub(m):
        tags_inner = m.group(1)
        # Strip packet-5/rlp5 markers
        tags_inner = tags_inner.replace('"packet-5"', '"packet-6"').replace('"rlp5"', '"rlp6"')
        extra_str = ", ".join(f'"{t}"' for t in extra_tags)
        return f"tags: [{tags_inner}, {extra_str}]"
    yaml = re.sub(r'tags: \[(.+?)\]', tag_sub, yaml, count=1, flags=re.DOTALL)
    return yaml


def write_yaml(filename: str, content: str) -> None:
    out = EXP_DIR / filename
    out.write_text(content)
    print(f"  wrote {out}")


