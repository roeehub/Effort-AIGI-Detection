def main() -> int:
    log.info("=" * 70)
    log.info("SBI_SCORE_COLLECTION_2026-05-07 — direct measurement of P8A/E2B/PA_3800 on SBI")
    log.info("=" * 70)
    log.info("output dir: %s", OUT_DIR)

    rng = np.random.RandomState(RNG_SEED)
    random.seed(RNG_SEED)

    # ──────── Step 1: Regenerate SBI pseudo-fakes (deterministic) ────────
    real_paths = collect_real_frames()
    log.info("real frames available: %d", len(real_paths))
    if len(real_paths) < 100:
        log.error("not enough real frames")
        return 2
    real_for_sbi = real_paths[:N_SBI_TARGET]
    log.info("using first %d real frames as SBI sources", len(real_for_sbi))

    mesher = mp.solutions.face_mesh.FaceMesh(
        max_num_faces=1, refine_landmarks=False, min_detection_confidence=0.3,
        static_image_mode=True,
    )

    log.info("[1/4] regenerating %d SBI pseudo-fakes (seed=%d) ...",
             len(real_for_sbi), RNG_SEED)
    t0 = time.time()
    sbi_images: list[np.ndarray] = []
    sbi_meta: list[dict] = []
    real_images: list[np.ndarray] = []  # we'll also score reals locally for parity
    n_landmarks_ok = 0
    for i, p in enumerate(real_for_sbi):
        img = cv2.imread(str(p), cv2.IMREAD_COLOR)
        if img is None:
            log.warning("decode-fail %s", p)
            continue
        result = make_sbi(img, mesher, rng)
        if result["landmarks_ok"]:
            n_landmarks_ok += 1
        sbi_images.append(result["sbi_image"])
        real_images.append(img)
        sbi_meta.append({
            "sbi_idx": i,
            "sbi_id": f"sbi_{i:04d}_{p.parent.name}_{p.stem}.png",
            "real_source_path": str(p),
            "real_source_basename": p.name,
            "real_source_identity": p.parent.name,
            "landmarks_ok": int(result["landmarks_ok"]),
        })
        if (i + 1) % 50 == 0:
            log.info("  %d/%d", i + 1, len(real_for_sbi))
    mesher.close()
    log.info("[1/4] done: landmarks_ok=%d/%d  elapsed=%.1fs",
             n_landmarks_ok, len(real_for_sbi), time.time() - t0)

    # Sanity: parity check vs sbi_smoke records (should be identical sources/order)
    if SBI_RECORDS_CSV.exists():
        prior = pd.read_csv(SBI_RECORDS_CSV)
        if len(prior) == len(sbi_meta):
            mismatches = 0
            for i, row in enumerate(prior.itertuples()):
                if row.real_source_basename != sbi_meta[i]["real_source_basename"]:
                    mismatches += 1
            log.info("parity vs sbi_smoke records: %d mismatches / %d",
                     mismatches, len(sbi_meta))
        else:
            log.warning("count mismatch: prior=%d  current=%d", len(prior), len(sbi_meta))

    # ──────── Step 2: Run inference on SBI through P8A / E2B / PA_3800 ────────
    sbi_scores_per_ckpt: dict[str, np.ndarray] = {}
    for ckpt_name, ckpt_path in CKPT_LOCAL.items():
        log.info("[2/4] %s on SBI ...", ckpt_name)
        if not Path(ckpt_path).exists():
            log.error("ckpt missing: %s — falling back to GCS download", ckpt_path)
            return 3
        sbi_scores_per_ckpt[ckpt_name] = score_with_ckpt(ckpt_path, sbi_images)
        log.info("[2/4] %s SBI mean=%.4f median=%.4f std=%.4f",
                 ckpt_name,
                 float(sbi_scores_per_ckpt[ckpt_name].mean()),
                 float(np.median(sbi_scores_per_ckpt[ckpt_name])),
                 float(sbi_scores_per_ckpt[ckpt_name].std(ddof=1)))

    # Also run inference on the SAME 200 reals locally so source + sbi pairing has
    # numerically comparable scores (cached scores were on full 224 source frames
    # via different preprocessing path; we want a clean apples-to-apples
    # source_local_score field). We will compare both.
    log.info("[2.5/4] running inference on the 200 source reals (local parity)...")
    real_scores_per_ckpt: dict[str, np.ndarray] = {}
    for ckpt_name, ckpt_path in CKPT_LOCAL.items():
        log.info("  %s on reals ...", ckpt_name)
        real_scores_per_ckpt[ckpt_name] = score_with_ckpt(ckpt_path, real_images)
        log.info("  %s real_local mean=%.4f median=%.4f",
                 ckpt_name,
                 float(real_scores_per_ckpt[ckpt_name].mean()),
                 float(np.median(real_scores_per_ckpt[ckpt_name])))

    # ──────── Step 3: Read cached real + cached fake scores ────────
    log.info("[3/4] reading cached real + fake scores ...")
    cached_real_scores: dict[str, list[float]] = {}
    cached_fake_scores: dict[str, list[float]] = {}
    score_files = {
        "P8A": ("team_sanity_may5_scores_P8A.csv", "live_fakes_scores_P8A.csv"),
        "E2B": ("team_sanity_may5_scores_E2B.csv", "live_fakes_scores_E2B.csv"),
        "PA_3800": ("team_sanity_may5_scores_PA_3800.csv", "live_fakes_scores_PA_3800.csv"),
    }
    for ckpt, (rfile, ffile) in score_files.items():
        ridx = load_score_index(SCORES_DIR / rfile)
        fidx = load_score_index(SCORES_DIR / ffile)
        # cached real for the same 200 sources
        rs: list[float] = []
        for p in real_for_sbi:
            v = ridx.get(gs_uri_from_real_local(p))
            if v is not None:
                rs.append(v)
        cached_real_scores[ckpt] = rs
        # cached fake — sample 200 deterministically
        all_fake_uris = list(fidx.keys())
        fake_rng = np.random.RandomState(RNG_SEED + 1)
        idxs = fake_rng.choice(len(all_fake_uris),
                                size=min(200, len(all_fake_uris)),
                                replace=False)
        cached_fake_scores[ckpt] = [fidx[all_fake_uris[i]] for i in idxs]
        log.info("  %s cached_real=%d  cached_fake=%d",
                 ckpt, len(rs), len(cached_fake_scores[ckpt]))

    # ──────── Step 4: Write outputs ────────
    log.info("[4/4] writing outputs ...")
    # 4a sbi_scores.csv  — one row per pseudo-fake
    rows = []
    for i, m in enumerate(sbi_meta):
        row = dict(m)
        for ckpt in CKPT_LOCAL:
            row[f"{ckpt}_sbi_score"] = float(sbi_scores_per_ckpt[ckpt][i])
            row[f"{ckpt}_real_source_score_local"] = float(real_scores_per_ckpt[ckpt][i])
        # cached real source score (apples-to-cached comparison)
        for ckpt, (rfile, _) in score_files.items():
            v = load_score_index(SCORES_DIR / rfile).get(
                gs_uri_from_real_local(Path(m["real_source_path"]))
            )
            row[f"{ckpt}_real_source_score_cached"] = float(v) if v is not None else float("nan")
        rows.append(row)
    df_scores = pd.DataFrame(rows)
    df_scores.to_csv(OUT_DIR / "sbi_scores.csv", index=False)
    log.info("  -> sbi_scores.csv (%d rows)", len(df_scores))

    # 4b score_distributions.csv
    dist_rows = []
    for ckpt in CKPT_LOCAL:
        sbi_arr = sbi_scores_per_ckpt[ckpt]
        real_local = real_scores_per_ckpt[ckpt]
        cached_real = np.array(cached_real_scores[ckpt])
        cached_fake = np.array(cached_fake_scores[ckpt])
        dist_rows.append({"ckpt": ckpt, "population": "sbi_pseudofake",
                          **summary_stats(sbi_arr),
                          "bimodality_coeff": bimodality_coeff(sbi_arr)})
        dist_rows.append({"ckpt": ckpt, "population": "real_source_local",
                          **summary_stats(real_local),
                          "bimodality_coeff": bimodality_coeff(real_local)})
        dist_rows.append({"ckpt": ckpt, "population": "real_source_cached",
                          **summary_stats(cached_real),
                          "bimodality_coeff": bimodality_coeff(cached_real)})
        dist_rows.append({"ckpt": ckpt, "population": "known_fake_cached",
                          **summary_stats(cached_fake),
                          "bimodality_coeff": bimodality_coeff(cached_fake)})
    df_dist = pd.DataFrame(dist_rows)
    df_dist.to_csv(OUT_DIR / "score_distributions.csv", index=False)
    log.info("  -> score_distributions.csv")

    # 4c score_d_table.csv — pairwise Cohen's d
    d_rows = []
    for ckpt in CKPT_LOCAL:
        sbi_arr = sbi_scores_per_ckpt[ckpt]
        real_local = real_scores_per_ckpt[ckpt]
        cached_real = np.array(cached_real_scores[ckpt])
        cached_fake = np.array(cached_fake_scores[ckpt])
        d_rows.append({
            "ckpt": ckpt,
            "d_real_local_vs_sbi":   cohen_d(real_local, sbi_arr),
            "d_cached_real_vs_sbi":  cohen_d(cached_real, sbi_arr),
            "d_sbi_vs_cached_fake":  cohen_d(sbi_arr, cached_fake),
            "d_cached_real_vs_cached_fake": cohen_d(cached_real, cached_fake),
            "d_real_local_vs_cached_fake":  cohen_d(real_local, cached_fake),
            # signed (sbi - real) / pooled — positive means SBI shifts toward fake
            "shift_sbi_minus_real_local": float(sbi_arr.mean() - real_local.mean()),
            "shift_sbi_minus_cached_real": float(sbi_arr.mean() - cached_real.mean()),
            "frac_sbi_above_05":      float(np.mean(sbi_arr > 0.5)),
            "frac_sbi_above_07":      float(np.mean(sbi_arr > 0.7)),
            "frac_sbi_above_09":      float(np.mean(sbi_arr > 0.9)),
            "frac_sbi_below_01":      float(np.mean(sbi_arr < 0.1)),
            "frac_sbi_below_03":      float(np.mean(sbi_arr < 0.3)),
        })
    df_d = pd.DataFrame(d_rows)
    df_d.to_csv(OUT_DIR / "score_d_table.csv", index=False)
    log.info("  -> score_d_table.csv")

    # 4d Per-pair Pearson r between SBI score and real source score (same source)
    pair_rows = []
    for ckpt in CKPT_LOCAL:
        sbi_arr = sbi_scores_per_ckpt[ckpt]
        real_local = real_scores_per_ckpt[ckpt]
        cached_real_paired: list[float] = []
        sbi_paired_for_cached: list[float] = []
        ridx = load_score_index(SCORES_DIR / score_files[ckpt][0])
        for i, m in enumerate(sbi_meta):
            v = ridx.get(gs_uri_from_real_local(Path(m["real_source_path"])))
            if v is not None:
                cached_real_paired.append(v)
                sbi_paired_for_cached.append(float(sbi_arr[i]))
        # pair stats
        r_local = float(np.corrcoef(real_local, sbi_arr)[0, 1]) if len(sbi_arr) > 1 else float("nan")
        r_cached = float(np.corrcoef(cached_real_paired, sbi_paired_for_cached)[0, 1]) if len(cached_real_paired) > 1 else float("nan")
        # delta distribution
        delta_local = sbi_arr - real_local
        pair_rows.append({
            "ckpt": ckpt,
            "pearson_r_sbi_vs_real_local":  r_local,
            "pearson_r_sbi_vs_real_cached": r_cached,
            "delta_mean":   float(delta_local.mean()),
            "delta_median": float(np.median(delta_local)),
            "delta_std":    float(delta_local.std(ddof=1)),
            "delta_p10":    float(np.percentile(delta_local, 10)),
            "delta_p90":    float(np.percentile(delta_local, 90)),
            "frac_delta_positive": float(np.mean(delta_local > 0)),
        })
    df_pair = pd.DataFrame(pair_rows)
    df_pair.to_csv(OUT_DIR / "pair_correlation.csv", index=False)
    log.info("  -> pair_correlation.csv")

    # 4e summary.json + verdict.json
    # Bimodality verdict per ckpt: BC > 0.555 ≈ bimodal
    bimodal_per_ckpt = {ckpt: float(bimodality_coeff(sbi_scores_per_ckpt[ckpt]))
                         for ckpt in CKPT_LOCAL}
    n_bimodal = sum(1 for v in bimodal_per_ckpt.values()
                    if v == v and v > 0.555)

    # Intermediate-collapse check: SBI median should be > real median AND < fake
    # median on at least 1 of 3 ckpts. Strict: SBI median ∈ (real_median, fake_median)
    intermediate_per_ckpt = {}
    for ckpt in CKPT_LOCAL:
        sbi_med = float(np.median(sbi_scores_per_ckpt[ckpt]))
        r_med = float(np.median(real_scores_per_ckpt[ckpt]))
        f_med = float(np.median(cached_fake_scores[ckpt])) if cached_fake_scores[ckpt] else float("nan")
        intermediate_per_ckpt[ckpt] = {
            "sbi_median": sbi_med,
            "real_local_median": r_med,
            "fake_cached_median": f_med,
            "is_intermediate": bool(r_med < sbi_med < f_med) if f_med == f_med else False,
            "is_above_real": bool(sbi_med > r_med),
        }
    n_intermediate = sum(1 for v in intermediate_per_ckpt.values()
                         if v["is_intermediate"])
    n_above_real = sum(1 for v in intermediate_per_ckpt.values()
                       if v["is_above_real"])

    # Verdict logic
    # GREEN-BY-DIRECT-MEASUREMENT  if:
    #   - SBI scores DO NOT collapse (frac_sbi>0.95 < 80% AND frac_sbi<0.05 < 80%) on majority ckpts
    #   - SBI median > real median on ≥2/3 ckpts (mass shift toward fake)
    #   - At least one ckpt shows bimodality OR std(SBI) > 1.5×std(real) (heterogeneous response)
    # AMBER if SBI is not collapsed but doesn't shift toward fake (median ≈ real)
    # RED   if SBI collapses to either extreme on majority ckpts
    n_collapsed = 0
    spread_richer_than_real = 0
    for ckpt in CKPT_LOCAL:
        sbi_arr = sbi_scores_per_ckpt[ckpt]
        real_local = real_scores_per_ckpt[ckpt]
        if (np.mean(sbi_arr > 0.95) > 0.80) or (np.mean(sbi_arr < 0.05) > 0.80):
            n_collapsed += 1
        if sbi_arr.std(ddof=1) > 1.5 * real_local.std(ddof=1):
            spread_richer_than_real += 1

    if n_collapsed >= 2:
        verdict = "RED"
        headline = ("RED: SBI scores collapse on majority of ckpts — "
                    "pseudofakes are not a usable training signal.")
    elif n_above_real >= 2 and (n_bimodal >= 1 or spread_richer_than_real >= 2):
        verdict = "GREEN"
        headline = ("GREEN-by-direct-measurement: SBI scores shift toward fake direction "
                    "on majority of ckpts, with heterogeneous response — pseudofakes "
                    "are a usable, method-agnostic training signal.")
    elif n_above_real >= 2:
        verdict = "GREEN"
        headline = ("GREEN-by-direct-measurement: SBI scores shift toward fake direction "
                    "on majority of ckpts. Spread is narrow but signal is non-degenerate.")
    elif n_above_real >= 1:
        verdict = "AMBER"
        headline = ("AMBER: SBI scores partially shift toward fake; effect is ckpt-dependent.")
    else:
        verdict = "AMBER"
        headline = ("AMBER: SBI scores do not collapse, but fail to shift toward fake on any ckpt.")

    summary = {
        "job": "SBI_SCORE_COLLECTION_2026-05-07",
        "phase": "0i",
        "n_sbi_pseudofakes_scored": int(len(sbi_scores_per_ckpt["P8A"])),
        "n_real_sources_scored_locally": int(len(real_scores_per_ckpt["P8A"])),
        "n_cached_real_matched": {ckpt: len(v) for ckpt, v in cached_real_scores.items()},
        "n_cached_fake_sampled": {ckpt: len(v) for ckpt, v in cached_fake_scores.items()},
        "landmark_detection_rate": float(n_landmarks_ok / max(len(real_for_sbi), 1)),
        "per_ckpt_score_summary": {
            ckpt: {
                "sbi": summary_stats(sbi_scores_per_ckpt[ckpt]),
                "real_local": summary_stats(real_scores_per_ckpt[ckpt]),
                "cached_real": summary_stats(np.array(cached_real_scores[ckpt])),
                "cached_fake": summary_stats(np.array(cached_fake_scores[ckpt])),
            }
            for ckpt in CKPT_LOCAL
        },
        "bimodality_coefficient_sbi": bimodal_per_ckpt,
        "n_ckpts_bimodal": int(n_bimodal),
        "intermediate_check": intermediate_per_ckpt,
        "n_ckpts_intermediate": int(n_intermediate),
        "n_ckpts_above_real": int(n_above_real),
        "n_ckpts_collapsed": int(n_collapsed),
        "n_ckpts_spread_richer_than_real": int(spread_richer_than_real),
        "verdict": verdict,
        "headline": headline,
    }
    with (OUT_DIR / "summary.json").open("w") as f:
        json.dump(summary, f, indent=2, default=float)

    verdict_blob = {
        "job": "SBI_SCORE_COLLECTION_2026-05-07",
        "phase": "0i",
        "verdict": verdict,
        "verdict_kind": "by_direct_measurement",
        "compares_to": "SBI_SMOKE_2026-05-06 GREEN-by-headroom",
        "p2_pe_sbi_launch_readiness": verdict,
        "headline": headline,
        "criteria": {
            "n_ckpts_above_real_median": int(n_above_real),
            "n_ckpts_bimodal_BC_gt_0p555": int(n_bimodal),
            "n_ckpts_collapsed": int(n_collapsed),
            "n_ckpts_intermediate_strict": int(n_intermediate),
        },
    }
    with (OUT_DIR / "verdict.json").open("w") as f:
        json.dump(verdict_blob, f, indent=2, default=float)
    log.info("  -> summary.json + verdict.json")
    log.info("VERDICT: %s — %s", verdict, headline)
    return 0


