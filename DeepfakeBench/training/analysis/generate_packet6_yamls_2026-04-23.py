def make_rlp6b(slot_id: str, name: str, desc: str, tags: list[str], mutator):
    """Generate an RLP6B yaml starting from the canary yaml.

    mutator takes the yaml text, returns modified text with the representation
    lever applied. name/desc/tags are applied via replace_name_desc_tags.
    """
    y = CANARY
    y = mutator(y)
    y = replace_name_desc_tags(y, name, desc, tags)
    # Rewrite top header
    y = _re.sub(
        r"^# ={5,}\n# R13_RLP6_01_gate_align_canary.*?^# ={5,}$",
        "# ============================================================================\n"
        f"# {name}\n"
        "# Phase 2, Round 13 - relaunch packet 6B (representation robustness).\n"
        "# Base = R13_RLP5_07_E3_seedB + packet-6 slot-1 gate-alignment changes.\n"
        f"# Representation lever: {desc}\n"
        "# ============================================================================",
        y,
        count=1,
        flags=_re.MULTILINE | _re.DOTALL,
    )
    write_yaml(f"{name}.yaml", y)


def add_quality_head_lambda(yaml: str, multiplier: float) -> str:
    """Enable quality-domain adversarial head and set its loss weight.

    Canary doesn't set this; default in detector is `use_quality_domain_head: False`.
    Enable explicitly + scale weight from the default 0.1. Note: requires the
    dataloader to provide `quality_domain` labels (see DOMAIN_MAP in
    effort_detector.py:250); if labels are missing the trainer raises unless
    quality_domain_require_labels is False — for an experiment we want strict.
    """
    weight = 0.1 * multiplier
    insertion = (
        f"use_quality_domain_head: true\n"
        f"quality_domain_loss_weight: {weight}\n"
        f"quality_domain_require_labels: true\n\n"
    )
    return yaml.replace("evaluate_every_steps: 500", insertion + "evaluate_every_steps: 500", 1)


def set_arcface_margin(yaml: str, new_m: float) -> str:
    return yaml.replace("arcface_m: 0.15", f"arcface_m: {new_m}")


def set_mixup_alpha(yaml: str, alpha: float) -> str:
    # Canary doesn't set mixup_alpha. Insert into the top-level training params area.
    return yaml.replace("stability_lambda: 0.0\n", f"stability_lambda: 0.0\nmixup_alpha: {alpha}\n", 1)


def set_label_smoothing_fake(yaml: str, smoothing: float) -> str:
    # Enable label_smoothing; configurable per-class support may not exist so use a uniform hyperparam
    # and document in desc that it applies to both classes in current codebase.
    return yaml.replace("label_smoothing: 0.0\n", f"label_smoothing: {smoothing}\n", 1)


def enable_feat_norm_reg(yaml: str, lam: float) -> str:
    insertion = f"feat_norm_reg_lambda: {lam}\n"
    return yaml.replace("stability_lambda: 0.0\n", f"stability_lambda: 0.0\n{insertion}", 1)


